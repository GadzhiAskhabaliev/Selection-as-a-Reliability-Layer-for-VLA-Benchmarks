"""Build two private Kaggle jobs without submitting or running inference."""
import base64
import hashlib
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    'baseline_runtime': 'kaggle/openvla_baseline/baseline.py',
    'consensus_selection': 'src/consensus_selection/__init__.py',
    'cs_pilot': 'experiments/offline/cs_pilot.py',
    'motion_pilot': 'experiments/offline/motion_pilot.py',
}


def build(name):
    config_path = ROOT / f'configs/motion/{name}.json'
    protocol = json.loads(config_path.read_text())
    hashes = {str(config_path.relative_to(ROOT)): hashlib.sha256(config_path.read_bytes()).hexdigest()}
    parts = ['# Generated by scripts/build_motion_kernels.py; edit source modules.\n',
             'import sys, types, json, base64, zlib\n']
    sources = dict(SOURCES)
    if protocol.get('episode_boundary_policy') == 'tfds_outer_record_v2':
        sources['record_boundaries'] = 'experiments/offline/record_boundaries.py'
    for module, relative in sources.items():
        source = (ROOT / relative).read_bytes()
        hashes[relative] = hashlib.sha256(source).hexdigest()
        packed = base64.b64encode(zlib.compress(source, 9)).decode()
        parts.append(f'{module} = types.ModuleType({module!r})\n'
                     f'{module}.__file__ = __file__\n'
                     f'sys.modules[{module!r}] = {module}\n'
                     f'exec(compile(zlib.decompress(base64.b64decode({packed!r})).decode(), '
                     f'{relative!r}, "exec"), {module}.__dict__)\n')
    parts.append(f'PROTOCOL = {protocol!r}\nSOURCE_HASHES = {hashes!r}\n')
    entry = '''
if __name__ == '__main__':
    baseline_runtime.OUT.mkdir(parents=True, exist_ok=True)
    baseline_runtime.save_json('bundle_sources.json', SOURCE_HASHES)
    try:
        motion_pilot.run(baseline_runtime, consensus_selection, cs_pilot, PROTOCOL)
    except Exception as exc:
        baseline_runtime.save_json('failure.json', {'type': type(exc).__name__, 'message': str(exc)})
        raise
'''
    if protocol.get('episode_boundary_policy') == 'tfds_outer_record_v2':
        entry = entry.replace('        motion_pilot.run(',
                              '        record_boundaries.install(baseline_runtime, PROTOCOL)\n'
                              '        motion_pilot.run(')
    parts.append(entry)
    folder = ROOT / f'kaggle/motion_{name}'
    folder.mkdir(parents=True, exist_ok=True)
    (folder / 'run.py').write_text(''.join(parts))
    (folder / 'source-hashes.json').write_text(json.dumps(hashes, indent=2) + '\n')
    label = 'Jaco' if name == 'jaco' else 'NYU Door'
    slug = 'jaco' if name == 'jaco' else 'nyu-door'
    metadata = {'id': f'stepanivanov233/multinet-openvla-{slug}-motion-cs8',
                'title': f'MultiNet OpenVLA {label} Motion CS8', 'code_file': 'run.py',
                'language': 'python', 'kernel_type': 'script', 'is_private': True,
                'enable_gpu': True, 'enable_tpu': False, 'enable_internet': True,
                'machine_shape': 'NvidiaTeslaT4',
                'dataset_sources': [], 'competition_sources': [], 'kernel_sources': [], 'model_sources': []}
    # Preserve ownership/IDs if a collaborator customizes metadata for their account.
    metadata_path = folder / 'kernel-metadata.json'
    if not metadata_path.exists():
        metadata_path.write_text(json.dumps(metadata, indent=2) + '\n')
    print(folder)


if __name__ == '__main__':
    for name in ('jaco', 'nyu_door'):
        build(name)
