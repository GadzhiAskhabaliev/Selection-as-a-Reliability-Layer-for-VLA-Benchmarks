"""Bundle local sources into a self-contained private Kaggle script; no uploads."""
import hashlib
import json
import argparse
import base64
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    'baseline_runtime': 'kaggle/openvla_baseline/baseline.py',
    'consensus_selection': 'src/consensus_selection/__init__.py',
    'cs_pilot': 'experiments/offline/cs_pilot.py',
}


def build(smoke=False):
    hashes = {}
    parts = ['# Generated by scripts/build_cs_kernel.py. Edit source modules, then rebuild.\n',
             'import json, sys, types, base64, zlib\nfrom pathlib import Path\n']
    sources = dict(SOURCES)
    if smoke:
        sources['cs_smoke'] = 'experiments/offline/cs_smoke.py'
    for name, relative in sources.items():
        source = (ROOT / relative).read_text()
        hashes[relative] = hashlib.sha256(source.encode()).hexdigest()
        # Keep the smoke upload small on unreliable API connections. Hashes refer
        # to the original readable source; compression does not change execution.
        if smoke:
            packed = base64.b64encode(zlib.compress(source.encode(), 9)).decode()
            source_expression = f'zlib.decompress(base64.b64decode({packed!r})).decode()'
        else:
            source_expression = repr(source)
        # baseline.bootstrap re-execs the bundle in its Python 3.11 environment.
        parts.append(f'{name} = types.ModuleType({name!r})\n'
                     f'{name}.__file__ = __file__\n'
                     f'sys.modules[{name!r}] = {name}\n'
                     f'exec(compile({source_expression}, {relative!r}, "exec"), {name}.__dict__)\n')
    parts.append(f'SOURCE_HASHES = {hashes!r}\n')
    entry = 'cs_smoke.run(baseline_runtime, consensus_selection, cs_pilot)' if smoke else 'cs_pilot.run(baseline_runtime, consensus_selection)'
    parts.append('''
if __name__ == '__main__':
    baseline_runtime.OUT.mkdir(parents=True, exist_ok=True)
    baseline_runtime.save_json('bundle_sources.json', SOURCE_HASHES)
    try:
        ENTRY_POINT
    except Exception as exc:
        baseline_runtime.save_json('failure.json', {'type': type(exc).__name__, 'message': str(exc)})
        raise
'''.replace('ENTRY_POINT', entry))
    target = ROOT / ('kaggle/openvla_cs_smoke/cs_smoke.py' if smoke else 'kaggle/openvla_cs/cs.py')
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(''.join(parts))
    (target.parent / 'source-hashes.json').write_text(json.dumps(hashes, indent=2) + '\n')
    print(target)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--smoke', action='store_true', help='Build the eight-frame integration check')
    build(smoke=parser.parse_args().smoke)
